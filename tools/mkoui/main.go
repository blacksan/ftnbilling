// mkoui turns the IEEE MA-L registry (oui.txt, the "(hex)" lines) into internal/billing/oui_ieee.go.
// It runs offline, on the file you give it; the server never downloads anything.
//
//	go run ./tools/mkoui oui.txt > internal/billing/oui_ieee.go
package main

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"sort"
	"strconv"
	"strings"
)

// parse reads "AA-BB-CC   (hex)\t\tVendor Name" lines and returns prefix ("AA:BB:CC") -> name.
func parse(r io.Reader) (map[string]string, error) {
	out := map[string]string{}
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		i := strings.Index(line, "(hex)")
		if i < 0 {
			continue
		}
		raw := strings.TrimSpace(line[:i])
		name := strings.Join(strings.Fields(line[i+len("(hex)"):]), " ")
		if len(raw) != 8 || raw[2] != '-' || raw[5] != '-' || name == "" || strings.EqualFold(name, "private") {
			continue
		}
		out[strings.ToUpper(strings.ReplaceAll(raw, "-", ":"))] = name
	}
	return out, sc.Err()
}

func render(m map[string]string, w io.Writer) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintln(w, "// Code generated by tools/mkoui from the IEEE MA-L registry; DO NOT EDIT.")
	fmt.Fprintln(w, "package billing")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "// ieeeOUI is the IEEE MA-L registry (24-bit prefixes) compiled in; nothing is looked up at run time.")
	fmt.Fprintln(w, "var ieeeOUI = map[string]string{")
	for _, k := range keys {
		fmt.Fprintf(w, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(m[k]))
	}
	fmt.Fprintln(w, "}")
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: mkoui oui.txt > internal/billing/oui_ieee.go")
		os.Exit(2)
	}
	f, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	m, err := parse(f)
	if err != nil || len(m) == 0 {
		fmt.Fprintln(os.Stderr, "no MA-L entries found", err)
		os.Exit(1)
	}
	render(m, os.Stdout)
}
